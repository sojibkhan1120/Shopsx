export const translate = (key: string, lang: string): string => {
  const translations = TRANSLATIONS[key];
  if (!translations) return key;
  // Exact match
  if (translations[lang]) return translations[lang];
  // Sub-code fallback (e.g. 'ar-SY' -> 'ar')
  const baseLang = lang.split('-')[0];
  if (translations[baseLang]) return translations[baseLang];
  // Arabic regional fallback (Syria, Lebanon, UAE, Egypt, Saudi Arabia)
  if (['sy', 'lb', 'ae', 'eg', 'ar', 'sa'].includes(lang) && translations['ar']) {
    return translations['ar'];
  }
  // Fallback to English
  return translations['en'] || key;
};
